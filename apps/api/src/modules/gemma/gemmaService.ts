/**
 * Gemma recommendation service.
 *
 * Flow:
 *  1. Build prompt from structured context
 *  2. Call Gemma via Ollama
 *  3. Parse JSON output
 *  4. Validate with guardrail
 *  5. If invalid → retry once with stricter instruction
 *  6. If retry also fails → deterministic fallback template
 *
 * The model name is one env var (OLLAMA_MODEL). Swapping
 * models — e.g. gemma3:8b, gemma3:27b, llama3 — requires
 * zero code changes.
 */

import { logger } from "../../config/logger.js";
import { env } from "../../config/env.js";
import { callGemma } from "./ollamaClient.js";
import { buildPrompt, SYSTEM_PROMPT, type PromptContext } from "./promptBuilder.js";
import { parseGemmaJson, validateOutput, type GemmaOutput } from "./guardrail.js";

// ── Types ─────────────────────────────────────────────────────────────────────

export interface RecommendationResult {
  pick: string;
  effectivePrice: number;
  reasons: string[];
  tradeoffs: string[];
  caveats: string[];
  /** "gemma" | "fallback" — tells UI which path was taken */
  source: "gemma" | "fallback";
  model: string;
  durationMs: number;
  guardrailHit: boolean;
}

// ── Deterministic fallback ────────────────────────────────────────────────────

function buildFallback(ctx: PromptContext): GemmaOutput {
  // Simply pick the cheapest in-stock offer within budget
  const sorted = [...ctx.offers]
    .filter((o) => o.inStock)
    .sort((a, b) => a.effectivePrice - b.effectivePrice);

  const pick = sorted[0] ?? ctx.offers[0];

  return {
    pick: pick.platform,
    effectivePrice: pick.effectivePrice,
    reasons: [
      `Lowest effective price (₹${pick.effectivePrice.toLocaleString("en-IN")}) among available options`,
      pick.discount > 0
        ? `Includes a ₹${pick.discount.toLocaleString("en-IN")} discount`
        : "No additional discount, but price is competitive",
      `Deal score: ${pick.dealScore.score}/10 — ${pick.dealScore.label}`,
    ],
    tradeoffs: sorted.length > 1
      ? [`${sorted[1].platform} is ₹${(sorted[1].effectivePrice - pick.effectivePrice).toLocaleString("en-IN")} more but may have different return policy`]
      : [],
    caveats: ["Recommendation generated by fallback logic — AI model unavailable or produced invalid output."],
  };
}

// ── Main service ──────────────────────────────────────────────────────────────

export async function getRecommendation(
  ctx: PromptContext
): Promise<RecommendationResult> {
  const start = Date.now();
  let guardrailHit = false;

  // Attempt 1
  try {
    const result1 = await callGemma([
      { role: "system", content: SYSTEM_PROMPT },
      { role: "user",   content: buildPrompt(ctx) },
    ]);

    const parsed1 = parseGemmaJson(result1.text);
    if (parsed1) {
      const validated1 = validateOutput(parsed1, ctx);
      if (validated1.valid && validated1.output) {
        return {
          ...validated1.output,
          source: "gemma",
          model: result1.model,
          durationMs: Date.now() - start,
          guardrailHit: false,
        };
      }
      guardrailHit = true;
      logger.warn("Gemma attempt 1 failed guardrail — retrying", {
        violations: validated1.violations,
      });
    } else {
      guardrailHit = true;
      logger.warn("Gemma attempt 1 returned unparseable JSON — retrying", {
        raw: result1.text.slice(0, 200),
      });
    }

    // Attempt 2 — stricter retry with violations fed back
    const retryUserMsg =
      buildPrompt(ctx) +
      `\n\nIMPORTANT: Your previous response had issues. Return ONLY raw JSON (no markdown). ` +
      `The "pick" field MUST be one of: ${ctx.offers.map((o) => o.platform).join(", ")}. ` +
      `The "effectivePrice" MUST match the offer's effective_price_inr exactly.`;

    const result2 = await callGemma([
      { role: "system", content: SYSTEM_PROMPT },
      { role: "user",   content: retryUserMsg },
    ]);

    const parsed2 = parseGemmaJson(result2.text);
    if (parsed2) {
      const validated2 = validateOutput(parsed2, ctx);
      if (validated2.valid && validated2.output) {
        return {
          ...validated2.output,
          source: "gemma",
          model: result2.model,
          durationMs: Date.now() - start,
          guardrailHit: true,   // retry was needed
        };
      }
    }

    logger.warn("Gemma retry also failed guardrail — using fallback", { model: env.OLLAMA_MODEL });
  } catch (err) {
    logger.error("Gemma call failed — using fallback", {
      err: (err as Error).message,
      model: env.OLLAMA_MODEL,
    });
    guardrailHit = true;
  }

  // Fallback — deterministic, always valid
  const fallback = buildFallback(ctx);
  return {
    ...fallback,
    source: "fallback",
    model: env.OLLAMA_MODEL,
    durationMs: Date.now() - start,
    guardrailHit,
  };
}
